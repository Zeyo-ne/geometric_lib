
def area(a, b):
    return a * b
'''поочередно приняв значения a и b(стороны прямоугольника), выводит его площадь,
полученную перемножением входных данных.'''


def perimeter(a, b):
    return 2 * (a + b)
'''поочередно приняв значения a и b(стороны прямоугольника), выводит его периметр,
полученный удвоением суммы входных данных.'''
